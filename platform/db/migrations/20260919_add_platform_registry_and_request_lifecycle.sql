create table if not exists public.platform_modules (
  module_key text primary key,
  name text not null,
  description text not null default '',
  category text not null default 'platform',
  status text not null default 'planned'
    check (status in ('live','beta','ready','planned','degraded','disabled')),
  route text,
  icon text,
  sort_order integer not null default 100,
  enabled boolean not null default true,
  capabilities text[] not null default '{}',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint platform_modules_key_format check (module_key ~ '^[a-z0-9][a-z0-9_-]{1,63}$')
);

alter table public.platform_modules enable row level security;

drop policy if exists "platform_modules_server_only" on public.platform_modules;
create policy "platform_modules_server_only"
on public.platform_modules
as restrictive
for all
to anon, authenticated
using (false)
with check (false);

create index if not exists platform_modules_enabled_sort_idx
  on public.platform_modules (enabled, sort_order, module_key);

drop trigger if exists platform_modules_touch_updated_at on public.platform_modules;
create trigger platform_modules_touch_updated_at
before update on public.platform_modules
for each row execute function public.touch_updated_at();

