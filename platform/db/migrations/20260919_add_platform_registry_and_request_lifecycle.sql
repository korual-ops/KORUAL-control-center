  on public.service_requests (idempotency_key)
  where idempotency_key is not null;

create table if not exists public.service_request_events (
  id bigint generated by default as identity primary key,
  request_id uuid not null references public.service_requests(id) on delete cascade,
  event_type text not null,
  from_status text,
  to_status text,
  actor_type text not null default 'system'
    check (actor_type in ('system','customer','provider','admin','automation')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.service_request_events enable row level security;

drop policy if exists "service_request_events_server_only" on public.service_request_events;
create policy "service_request_events_server_only"
on public.service_request_events
as restrictive
for all
to anon, authenticated
using (false)
with check (false);

create index if not exists service_request_events_request_created_idx
  on public.service_request_events (request_id, created_at desc);

create index if not exists service_request_events_type_created_idx
  on public.service_request_events (event_type, created_at desc);

create or replace function public.record_service_request_lifecycle()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  v_event_type text;
begin
  if tg_op = 'INSERT' then
    v_event_type := 'created';

    insert into public.service_request_events
      (request_id,event_type,from_status,to_status,actor_type,metadata)
    values
      (new.id,v_event_type,null,new.status,'system',
       jsonb_build_object('source',new.source,'request_code',new.request_code));

    insert into public.cloud_events
      (event_type,source,aggregate_type,aggregate_id,payload,status)
    values
      ('marketplace.service_request.created','marketplace','service_request',new.id::text,
       jsonb_build_object('request_code',new.request_code,'status',new.status),'queued');

    return new;
  end if;

  if tg_op = 'UPDATE' and new.status is distinct from old.status then
    v_event_type := 'status_changed';

    insert into public.service_request_events
      (request_id,event_type,from_status,to_status,actor_type,metadata)
    values
      (new.id,v_event_type,old.status,new.status,'system',
       jsonb_build_object('request_code',new.request_code));

    insert into public.cloud_events
      (event_type,source,aggregate_type,aggregate_id,payload,status)
    values
      ('marketplace.service_request.status_changed','marketplace','service_request',new.id::text,
       jsonb_build_object('request_code',new.request_code,'from_status',old.status,'to_status',new.status),'queued');
  end if;

  return new;
end;
$$;

revoke all on function public.record_service_request_lifecycle() from public, anon, authenticated;

drop trigger if exists service_requests_lifecycle_event_trg on public.service_requests;
create trigger service_requests_lifecycle_event_trg
after insert or update of status on public.service_requests
for each row execute function public.record_service_request_lifecycle();
